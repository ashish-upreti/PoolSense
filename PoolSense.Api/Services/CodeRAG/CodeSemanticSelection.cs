namespace PoolSense.Api.Services.CodeRAG;

internal static class CodeSemanticSelection
{
    internal sealed record Candidate(string Id, string Text, string Hash, string Path, int StartLine = 0,
        bool RecoveryPriority = false, bool UsefulForSelection = true);
    private static readonly HashSet<string> ExcludedDirectories = new(StringComparer.OrdinalIgnoreCase)
    {
        "node_modules", "vendor", "vendors", "generated", "dist", "build", "bin", "obj",
        ".git", "assets", "wwwroot", "packages", "coverage", "third_party", "third-party"
    };
    private static readonly HashSet<string> Extensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".cs", ".fs", ".vb", ".js", ".jsx", ".ts", ".tsx", ".py", ".go", ".java",
        ".kt", ".rs", ".rb", ".php", ".c", ".cpp", ".h", ".sql", ".sh", ".ps1",
        ".yaml", ".yml"
    };

    internal static bool Useful(string path, string source)
    {
        var parts = path.Replace('\\', '/').Split('/');
        var file = parts[^1];
        return !parts.Any(ExcludedDirectories.Contains)
            && Extensions.Contains(System.IO.Path.GetExtension(file))
            && !file.Contains(".g.", StringComparison.OrdinalIgnoreCase)
            && !file.Contains(".generated.", StringComparison.OrdinalIgnoreCase)
            && !file.Contains(".min.", StringComparison.OrdinalIgnoreCase)
            && !file.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase)
            && !source.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase)
            && !source.Contains("@generated", StringComparison.OrdinalIgnoreCase)
            && source.Any(char.IsLetterOrDigit);
    }

    // Never normalize interior whitespace: it can change string literals and indentation-sensitive code.
    internal static string UniqueSource(string source) =>
        source.Replace("\r\n", "\n", StringComparison.Ordinal).Trim();

    internal static List<Candidate> Select(List<Candidate> candidates, IEnumerable<string> cachedHashes, int target)
    {
        var cached = cachedHashes.ToHashSet(StringComparer.Ordinal);
        var result = candidates.Where(candidate => cached.Contains(candidate.Hash))
            .OrderBy(candidate => candidate.Hash, StringComparer.Ordinal).Take(target).ToList();
        var selected = result.Select(candidate => candidate.Id).ToHashSet(StringComparer.Ordinal);
        foreach (var candidate in candidates.Where(candidate => candidate.RecoveryPriority && !selected.Contains(candidate.Id))
            .OrderBy(candidate => candidate.Hash, StringComparer.Ordinal))
        {
            if (result.Count == target) break;
            result.Add(candidate);
            selected.Add(candidate.Id);
        }
        var groups = candidates.Where(candidate => !selected.Contains(candidate.Id))
            .GroupBy(candidate => Bucket(candidate.Path), StringComparer.Ordinal)
            .OrderBy(group => group.Key, StringComparer.Ordinal)
            .Select(group => new Queue<Candidate>(group.OrderBy(candidate => candidate.Hash, StringComparer.Ordinal)))
            .ToArray();
        while (result.Count < target && groups.Any(group => group.Count > 0))
            foreach (var group in groups)
            {
                if (result.Count == target) break;
                if (group.TryDequeue(out var candidate)) result.Add(candidate);
            }
        return result;
    }

    private static string Bucket(string path)
    {
        var parts = path.Replace('\\', '/').Split('/', StringSplitOptions.RemoveEmptyEntries);
        return string.Join('/', parts.SkipLast(1).Take(2)).ToLowerInvariant()
            + "|" + System.IO.Path.GetExtension(parts[^1]).ToLowerInvariant();
    }
}
